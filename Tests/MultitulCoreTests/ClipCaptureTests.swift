import Testing
import Foundation
import AppKit
@testable import MultitulCore

@Suite struct ClipCaptureTests {
    private func eval(_ items: [PasteboardItemData], source: AppIdentity? = Clp.safari, _ s: ClipSettings = ClipSettings(), own: String? = nil) -> ClipCaptureResult {
        ClipCapture.evaluate(Clp.snap(items, source: source), settings: s, ownBundleID: own)
    }

    @Test func plainTextIsRecorded() {
        guard case .record(let c) = eval([Clp.text("Привет, мир")]) else { Issue.record("not recorded"); return }
        #expect(c.kind == .text)
        #expect(c.title == "Привет, мир")
        #expect(c.search == "привет, мир")
        #expect(c.reps.count == 1)
        #expect(c.source == Clp.safari)
    }

    @Test func emptyAndWhitespaceFreeSnapshotsAreSkipped() {
        #expect(eval([]) == .skip(.empty))
        #expect(eval([Clp.text("")]) == .skip(.empty))
    }

    @Test func concealedTypeIsSkipped() {
        let it = Clp.text("пароль", extra: [PBType.concealed: Data()])
        #expect(eval([it]) == .skip(.concealed))
        var s = ClipSettings()
        s.skipConcealed = false
        #expect({ if case .record = eval([it], s) { return true } else { return false } }())
    }

    @Test func transientAndAutoGeneratedAreSkipped() {
        #expect(eval([Clp.text("x1", extra: [PBType.transient: Data()])]) == .skip(.transient))
        #expect(eval([Clp.text("x2", extra: [PBType.autoGenerated: Data()])]) == .skip(.transient))
        #expect(eval([Clp.text("x3", extra: ["com.agilebits.onepassword": Data()])]) == .skip(.concealed))
    }

    @Test func ignoredAndOwnAppsAreSkipped() {
        var s = ClipSettings()
        s.ignoredApps = ["com.apple.Safari"]
        #expect(eval([Clp.text("a")], s) == .skip(.ignoredApp))
        #expect(eval([Clp.text("a")], source: Clp.notes, own: "com.apple.Notes") == .skip(.ignoredApp))
    }

    @Test func passwordLikeTextIsSkippedButCanBeAllowed() {
        #expect(eval([Clp.text("P@ssw0rd!x")]) == .skip(.sensitive))
        var s = ClipSettings()
        s.skipSensitive = false
        #expect({ if case .record = eval([Clp.text("P@ssw0rd!x")], s) { return true } else { return false } }())
    }

    @Test func imagesRequireTheSetting() {
        let png = Clp.png(width: 10, height: 7)
        let item = PasteboardItemData(reps: [PBType.png: png])
        #expect(eval([item]) == .skip(.typeDisabled))
        var s = ClipSettings()
        s.keepImages = true
        guard case .record(let c) = eval([item], s) else { Issue.record("not recorded"); return }
        #expect(c.kind == .image)
        #expect(c.title == "Изображение 10×7")
    }

    @Test func textWinsOverImageWhenBothPresent() {
        var s = ClipSettings()
        s.keepImages = true
        let it = Clp.text("подпись", extra: [PBType.png: Clp.png()])
        guard case .record(let c) = eval([it], s) else { Issue.record("not recorded"); return }
        #expect(c.kind == .text)
    }

    @Test func filesAreRecordedAsPathsOnlyWhenEnabled() {
        let items = [Clp.fileItem("/Users/me/Док 1.pdf"), Clp.fileItem("/Users/me/b.txt")]
        #expect(eval(items) == .skip(.typeDisabled))
        var s = ClipSettings()
        s.keepFiles = true
        guard case .record(let c) = eval(items, s) else { Issue.record("not recorded"); return }
        #expect(c.kind == .files)
        #expect(c.reps.count == 2)
        #expect(c.reps.map(\.index) == [0, 1])
        #expect(c.search.contains("док 1.pdf"))
        #expect(c.title.hasPrefix("2 файл."))
    }

    @Test func colorsProduceHexTitle() {
        let data = Clp.colorData(NSColor(srgbRed: 1, green: 0.5, blue: 0, alpha: 1))
        guard case .record(let c) = eval([PasteboardItemData(reps: [PBType.color: data])]) else { Issue.record("not recorded"); return }
        #expect(c.kind == .color)
        #expect(c.title == "#FF8000")
    }

    @Test func richTextKeepsRtfAndHtmlOnlyWhenEnabled() {
        let rtf = try! NSAttributedString(string: "жирный").data(from: NSRange(location: 0, length: 6), documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf])
        let it = Clp.text("жирный", extra: [PBType.rtf: rtf, PBType.html: Data("<b>жирный</b>".utf8)])
        guard case .record(let rich) = eval([it]) else { Issue.record("not recorded"); return }
        #expect(rich.kind == .rich)
        #expect(Set(rich.reps.map(\.type)) == [PBType.utf8, PBType.rtf, PBType.html])
        var s = ClipSettings()
        s.keepRich = false
        guard case .record(let plain) = eval([it], s) else { Issue.record("not recorded"); return }
        #expect(plain.kind == .text)
        #expect(plain.reps.count == 1)
        #expect(rich.hash == plain.hash)
    }

    @Test func oversizedAndOverlongAreSkipped() {
        var s = ClipSettings()
        s.maxItemKB = 16
        #expect(eval([Clp.text(String(repeating: "a b ", count: 6000))], s) == .skip(.tooLarge))
        var t = ClipSettings()
        t.maxTextChars = 1000
        #expect(eval([Clp.text(String(repeating: "word ", count: 400))], t) == .skip(.tooLarge))
    }

    @Test func wantedTypesFollowSettings() {
        #expect(ClipCapture.wantedTypes(ClipSettings()) == [PBType.utf8, PBType.rtf, PBType.html, PBType.color])
        var s = ClipSettings()
        s.keepRich = false; s.keepColors = false; s.keepImages = true; s.keepFiles = true
        #expect(ClipCapture.wantedTypes(s) == [PBType.utf8, PBType.png, PBType.tiff, PBType.fileURL])
    }

    @Test func titleLineCollapsesAndTruncates() {
        #expect(ClipCapture.titleLine("\n\n  первая   строка \nвторая") == "первая строка")
        #expect(ClipCapture.titleLine(String(repeating: "я", count: 300)).count == 161)
    }
}

@Suite struct SensitiveTextTests {
    @Test(arguments: [
        "P@ssw0rd!x", "ghp_abcdefghijklmnopqrstuvwxyz0123456789", "sk-proj-abcdefghijklmnop1234567890",
        "AKIAIOSFODNN7EXAMPLE", "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.dozjgNryP4J3jVmNHl0w5N_XgL0n3I9PlFUP0THsR8U",
        "-----BEGIN RSA PRIVATE KEY-----\nMIIE\n-----END RSA PRIVATE KEY-----", "Bearer abcdef1234567890abcdef", "xK9fQ2mZ7vB4nL8cR1tY6wP3"
    ])
    func detectsSecrets(_ s: String) { #expect(SensitiveText.looksSecret(s)) }

    @Test(arguments: [
        "Привет, как дела?", "https://example.com/path?a=B1&c=d2", "john.smith1@example.com", "/Users/me/Documents/file-1.txt",
        "Hello123", "2026-10-23", "нормальное предложение с цифрами 12345", "getUserNameFromDatabase", "", "   "
    ])
    func ignoresOrdinaryText(_ s: String) { #expect(!SensitiveText.looksSecret(s)) }
}
