    public static let all: [EmojiEntry] = source.compactMap { line in
        let p = line.split(separator: "|", omittingEmptySubsequences: false).map(String.init)
        guard p.count == 3, !p[0].isEmpty else { return nil }
        return EmojiEntry(emoji: p[0], ru: p[1].split(separator: ",").map(String.init), en: p[2].split(separator: ",").map(String.init))
    }

    public static func search(_ query: String, limit: Int = 30, entries: [EmojiEntry] = EmojiTable.all) -> [EmojiEntry] {
        scored(query, limit: limit, entries: entries).map(\.entry)
    }

    static let defaultKeys: [[FuzzyKey]] = all.map { $0.keywords.map { FuzzyKey($0) } }

    public static func scored(_ query: String, limit: Int = 30, entries: [EmojiEntry] = EmojiTable.all) -> [(entry: EmojiEntry, score: Double)] {
        let q = FuzzyQuery(query)
        guard !q.isEmpty else { return [] }
        let useDefault = entries.count == all.count && entries.first?.emoji == all.first?.emoji
        let trimmed = query.trimmingCharacters(in: .whitespaces)
        var hits: [(Int, Double)] = []
        for (i, e) in entries.enumerated() {
            if e.emoji == trimmed { hits.append((i, 200)); continue }
            var best = 0.0
            let keys = useDefault ? defaultKeys[i] : e.keywords.map { FuzzyKey($0) }
            for (k, key) in keys.enumerated() {
                guard let s = Fuzzy.score(q, key), s.kind >= .wordPrefix || (s.kind >= .substring && q.norm.count >= 3) else { continue }
                var v = s.value
                if k != 0 && k != e.ru.count { v *= Fuzzy.secondaryKeyPenalty }
                best = max(best, v)
            }
            if best > 0 { hits.append((i, best)) }
        }
        hits.sort { $0.1 != $1.1 ? $0.1 > $1.1 : $0.0 < $1.0 }
        return hits.prefix(limit).map { (entries[$0.0], min($0.1, 100)) }
    }
