    public static let curated: [SettingsIndexEntry] =
        nav + app + netPages + systemPages + storagePages + displayPages + windowsPages + inputPages + soundPages
        + clipPages + toolPages + energyPages + islandPages + more

    public static let modules: [SettingsIndexEntry] = ModuleID.allCases.map {
        let info = $0.info
        return SettingsIndexEntry(title: info.title, keywords: info.summary, section: NavCatalog.sidebarID(for: $0))
    }

    public static let all: [SettingsIndexEntry] = {
        var out = curated
        var at: [String: Int] = [:]
        for (n, e) in out.enumerated() { at[e.section + "/" + e.title] = n }
        for m in modules {
            if let n = at[m.section + "/" + m.title] {
                let c = out[n]
                out[n] = SettingsIndexEntry(title: c.title, keywords: c.keywords + " " + m.keywords, section: c.section, subpage: c.subpage)
            } else {
                at[m.section + "/" + m.title] = out.count
                out.append(m)
            }
        }
        return out
    }()
