public struct AppIdentity: Equatable, Hashable, Sendable {
    public var bundleID: String?
    public var name: String?
    public var pid: Int32

    public init(bundleID: String?, name: String? = nil, pid: Int32 = 0) {
        self.bundleID = bundleID
        self.name = name
        self.pid = pid
    }
}

public struct PasteboardItemData: Equatable, Sendable {
    public var reps: [String: Data]

    public init(reps: [String: Data] = [:]) { self.reps = reps }

    public init(text: String) { self.reps = [PBType.utf8: Data(text.utf8)] }

    public var string: String? { reps[PBType.utf8].flatMap { String(data: $0, encoding: .utf8) } }
}

public struct ClipSnapshot: Equatable, Sendable {
    public var changeCount: Int
    public var types: [String]
    public var items: [PasteboardItemData]
    public var source: AppIdentity?

    public init(changeCount: Int, types: [String], items: [PasteboardItemData], source: AppIdentity? = nil) {
        self.changeCount = changeCount
        self.types = types
        self.items = items
        self.source = source
    }
}

