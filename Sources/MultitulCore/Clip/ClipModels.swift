import Foundation

public enum ClipKind: String, CaseIterable, Sendable {
    case text, rich, image, files, color

    public var title: String {
        switch self {
        case .text: "Текст"
        case .rich: "Форматированный текст"
        case .image: "Изображение"
        case .files: "Файлы"
        case .color: "Цвет"
        }
    }

    public var symbol: String {
        switch self {
        case .text: "text.alignleft"
        case .rich: "textformat"
        case .image: "photo"
        case .files: "doc"
        case .color: "paintpalette"
        }
    }
}

