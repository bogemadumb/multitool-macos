public struct ClipSettings: Equatable, Sendable {
    public var maxItems = 50
    public var maxAgeDays = 30
    public var keepRich = true
    public var keepImages = false
    public var keepFiles = false
    public var keepColors = true
    public var maxItemKB = 8192
    public var maxTotalMB = 256
    public var maxTextChars = 500_000
    public var skipSensitive = true
    public var skipConcealed = true
    public var skipTransient = true
    public var ignoredApps: [String] = ClipSettings.defaultIgnoredApps
    public var autoClearSeconds = 0
    public var clearOnSleep = false
    public var clearOnLock = false
    public var menuBarPreview = false
    public var pasteOnPick = true
    public var pollInterval = 0.5

    public init() {}

    public static let defaultIgnoredApps = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.apple.keychainaccess", "com.apple.Passwords"
    ]
    public static let countChoices = [20, 50, 100, 200, 500]
    public static let ageChoices = [1, 7, 30, 90, 0]
    public static let clearChoices = [0, 15, 30, 60, 120, 300]

    public var sanitized: ClipSettings {
        var s = self
        s.maxItems = max(5, min(s.maxItems, 5000))
        s.maxAgeDays = max(0, min(s.maxAgeDays, 3650))
        s.maxItemKB = max(16, min(s.maxItemKB, 262_144))
        s.maxTotalMB = max(8, min(s.maxTotalMB, 8192))
        s.maxTextChars = max(1000, min(s.maxTextChars, 10_000_000))
        s.autoClearSeconds = max(0, min(s.autoClearSeconds, 3600))
        s.pollInterval = max(0.2, min(s.pollInterval, 3))
        var seen = Set<String>()
        s.ignoredApps = s.ignoredApps.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty && seen.insert($0).inserted }
        return s
    }
}

