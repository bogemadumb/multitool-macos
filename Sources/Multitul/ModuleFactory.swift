import MultitulCore

@MainActor
func makeModule(_ id: ModuleID) -> Module {
    switch id {
    case .vpn: VpnModule()
    case .monitorCPU, .monitorGPU, .monitorMemory, .monitorNetwork, .monitorDisk, .monitorPower, .connectedDevices: MonitorModule(id: id)
    case .storozh: StorozhModule()
    case .killProcess, .portManager: SimpleModule(id: id)
    case .fanControl: FanControlModule()
    case .diskClean, .ramClean, .razbor, .cleaner, .uninstaller: CleanModule(id: id)
    case .liveWallpaper: LiveWallpaperModule()
    case .staticWallpaper: StaticWallpaperModule()
    case .monitorToggle: MonitorToggleModule()
    case .tvScreen: TvScreenModule()
    case .brightness: BrightnessModule()
    case .extraBrightness: ExtraBrightnessModule()
    case .keepAwake: KeepAwakeModule()
    case .bluetoothSleep: BluetoothSleepModule()
    case .gameMode: GameModeModule()
    case .autoPip: AutoPipModule()
    case .quickLauncher: QuickLauncherModule()
    case .commandBar: CommandBarModule()
    case .radialMenu: RadialMenuModule()
    case .quickToggles: QuickTogglesModule()
    case .colorPicker: ColorPickerModule()
    case .screenOcr: ScreenOcrModule()
    case .screenshot: ScreenshotModule()
    case .screenRecorder: RecorderModule()
    case .cleaningMode: CleaningModeModule()
    case .cameraPreview: CameraPreviewModule()
    case .scratchpad: ScratchpadModule()
    case .mediaTools: MediaToolsModule()
    case .homebrewManager: HomebrewModule()
    case .appUpdates: AppUpdatesModule()
    case .soundOutputSwitcher: OutputSwitcherModule()
    case .audioPriority: AudioPriorityModule()
    case .micMute: MicMuteModule()
    case .musicBlock: MusicBlockModule()
    case .mixer: MixerModule()
    case .clipboardHistory: ClipboardHistoryModule()
    case .pastePlain: PastePlainModule()
    case .urlCleaner: UrlCleanerModule()
    case .dmgInstaller: DmgInstallerModule()
    case .finderCutPaste: FinderCutPasteModule()
    case .finderRename: FinderRenameModule()
    case .shelf: ShelfModule()
    case .scrollInverter, .scrollHorizontal, .linearScroll, .smoothScroll, .scrollZoom, .mouseAcceleration, .mouseClickDebounce, .keyboardDebounce, .focusFollowsMouse,
         .mouseNavigation, .mouseButtonShortcuts, .middleClick, .superKey, .quitProtection, .textSnippets: InputModule(id: id)
    case .windowLayout, .windowMaximizer, .autoQuit, .spacesOrder, .dockClick, .windowSwitcher, .dockPreview: WindowsModule(id: id)
    case .notch: NotchModule()
    case .notchCalendar, .notchNotifications, .notchTimer, .notchAccessories, .notchLyrics, .notchQueue, .notchLiveEq, .notchDownloads, .notchWatch, .notchMascot:
        makeIslandExtModule(id)
    case .demoClock: DemoClockModule()
    case .demoHotkey: DemoHotkeyModule()
    case .demoAccessibility: DemoAccessibilityModule()
    }
}
